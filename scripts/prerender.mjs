/**
 * Bakes one real HTML file per route into `dist/`.
 * Runs automatically after `vite build`; run alone with: npm run prerender
 *
 * The problem this solves. xelvic.com is a client-rendered React app: every
 * URL served the same `index.html`, and the head in that file described the
 * home page. React then rewrote the tags on mount — but only for clients that
 * run React. A link pasted into WhatsApp, Slack, Discord, iMessage, X or
 * LinkedIn is fetched by a bot that does not execute JavaScript and does not
 * wait for one. So every share of every route produced the same card, carrying
 * the home page's title and the home page's image, which is exactly what the
 * screenshots showed.
 *
 * What this does. After Vite writes `dist/index.html`, this script reads the
 * route table in `src/seo/routes.ts` and writes `dist/<route>/index.html` for
 * every route in it — same bundle, same markup, different head. The tags come
 * from the same table `useSEO` reads at runtime, so the document a crawler
 * fetches and the document a browser renders cannot disagree: there is one
 * table and both sides read it.
 *
 * The head itself is built by `scripts/lib/html.mjs`, which the dev server
 * also uses to swap the head on the HTML it serves. Same function, same
 * strings, so what a preview shows while iterating and what ships are the same
 * document rather than two that look alike.
 *
 * What this does not do. It does not render the React tree, so the body stays
 * `<div id="root">`. Googlebot runs the bundle and sees the real page; the
 * bots that do not get the head, the structured data and the `<noscript>`
 * fallback, which is what they were ever going to read.
 *
 * Hosting note: this produces directory-style files (`dist/about/index.html`).
 * Every static host — Netlify, Vercel, Cloudflare Pages, GitHub Pages, S3 with
 * the website endpoint, nginx with `index` — serves those at `/about` without
 * a rewrite rule. A catch-all SPA rewrite must not shadow them; it should be a
 * fallback (200 only when the file is missing), which is what `netlify.toml` /
 * `vercel.json` do by default and what the `_redirects` written at the bottom
 * of this file spells out for hosts that need it.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadSeo, root } from './lib/seo-bundle.mjs'
import { assertSingleHead, htmlFor, NOT_FOUND, prepareShell } from './lib/html.mjs'

const seo = await loadSeo()
const distDir = resolve(root, 'dist')
const shell = prepareShell(readFileSync(resolve(distDir, 'index.html'), 'utf8'))

let written = 0

for (const r of seo.routes) {
  const html = assertSingleHead(htmlFor(shell, r, seo), r.path)
  if (r.path === '/') {
    writeFileSync(resolve(distDir, 'index.html'), html)
  } else {
    const dir = resolve(distDir, r.path.replace(/^\//, ''))
    mkdirSync(dir, { recursive: true })
    writeFileSync(resolve(dir, 'index.html'), html)
  }
  written += 1
}

/* A real 404 document. Hosts that have one serve it instead of the home page
   for a URL that is not in the table. */
writeFileSync(
  resolve(distDir, '404.html'),
  assertSingleHead(htmlFor(shell, NOT_FOUND, seo), '/404'),
)
written += 1

/* Some hosts only honour a redirects file, and the common SPA rewrite is the
   exact bug this script exists to fix: `/*  /index.html  200` answers every
   route with the home page's copy, so a crawler asking for /about gets the
   home page no matter what is on disk. Every route is a real file now, so the
   only rule that should exist is the one for a URL that is not in the table.
   Static files take precedence over these rules on both Netlify and Cloudflare
   Pages, so the built pages are served as built. */
writeFileSync(
  resolve(distDir, '_redirects'),
  [
    '# Generated by scripts/prerender.mjs — do not hand-edit.',
    '#',
    '# Every route in src/seo/routes.ts is a real HTML file in this build, and',
    '# the host serves those before it reads this file. The rule below is only',
    '# the fallback for a URL that is not in the table.',
    '/*  /404.html  404',
    '',
  ].join('\n'),
)

console.log(`✓ prerendered ${written} HTML documents into dist/`)
